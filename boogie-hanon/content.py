"""
Содержание сборника «Буги-вуги Ганон».

Музыкальный материал задаётся ступенями лада относительно тоники,
поэтому любое упражнение переносится в любую тональность без потери
правописания знаков.

Формат события (Event):
    degrees  — список ступеней снизу вверх, каждая как (степень, октава)
               степень: '1','2','b3','3','4','b5','5','6','b7','7'
               октава:  0 = основная, 1 = октавой выше, и т. д.
               None вместо списка = пауза
    ql       — длительность в четвертях
    fingers  — аппликатура снизу вверх, список строк той же длины, либо None
    accent   — акцент на событии
    grace    — ступени форшлага (перечёркнутого), берётся перед событием
"""

# --- квинтовый круг, по которому идёт секвенция ------------------------------
# секвенция начинается с F и возвращается в C: тоника не дублирует вступительную модель.
# C# и F# вместо Db и Gb — иначе ♭7 записывается как Cb и Fb, что нечитаемо.
CIRCLE_OF_FOURTHS = ['F', 'B-', 'E-', 'A-', 'C#', 'F#', 'B', 'E', 'A', 'D', 'G', 'C']


def ev(degrees, ql, fingers=None, accent=False, grace=None):
    return {'degrees': degrees, 'ql': ql, 'fingers': fingers,
            'accent': accent, 'grace': grace}


def rest(ql):
    return ev(None, ql)


