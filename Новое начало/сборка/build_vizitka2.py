NB = " "

doc = new_document("Конструкция-визитка", "материал для обсуждения")
hnum = add_multilevel_heading_numbering(doc)

doc_title(doc, "Партнёрство банковского капитала и девелоперской компетенции",
          "Рабочие конструкции сделок и механика разбора земельного навеса",
          f"Август 2026{NB}г. · версия 0.2 (черновик для кулуарных разговоров, не оферта)")

heading(doc, "Почему это своевременно", 1, hnum)
nb = add_list_numbering(doc, "decimal")
list_item(doc, "**Земля недоступна в кредит.** Бридж под площадку на пике ставки стоил "
          "25–26% годовых и убивал экономику проекта. Вход в новые площадки идёт "
          "через КРТ, выкуп у проблемных игроков и партнёрства с землевладельцами.", nb)
list_item(doc, "**Банкам не хватает equity в проектах.** Покрытие долга эскроу упало "
          "с 88% до ~70%, андеррайтинг смотрит на всю группу. Проекты с землёй "
          "и разрешением получают отказы из-за расчётного покрытия.", nb)
list_item(doc, "**Компетенция и капитал разъехались по разным рукам.** У девелоперов — "
          "команды и опыт, но дорогие деньги; у держателей капитала — деньги без "
          "аппетита к стройке. Нужна конструкция, в которой вклад каждой стороны "
          "измерим и защитим.", nb)
list_item(doc, "**Отрасль сама назвала тему года:** «От кредитования к совместному "
          "бизнесу» (форум «Движение»-2026). Банки начали входить в проекты как "
          "партнёры и соинвесторы.", nb)

heading(doc, "Земельный навес: кто примет убыток", 1, hnum)
heading(doc, "Масштаб", 2, hnum)
para(doc, "За годы дешёвых денег девелоперы сформировали земельные банки, "
     "потенциал застройки которых кратно — по экспертной оценке, в два-три "
     "раза — превышает реальный спрос. Значительная часть этих площадок куплена "
     "в 2020–2023 гг. на пике оптимизма, на бриджах, и стоит на балансах по ценам "
     "рынка, которого больше нет. Косвенные подтверждения по запущенным проектам: "
     "распроданность домов с вводом 2026 г. — 52% при норме ~70%; 27% строящегося "
     "портфеля — в зоне недостаточного спроса; срок реализации остатков — 3,2 года "
     "по стране и до 5,4 лет на юге (ДОМ.РФ, 2026).")
heading(doc, "Механика тупика", 2, hnum)
para(doc, "Девелопер не может продать площадку ниже цены покупки плюс бридж — это "
     "кристаллизация убытка, нарушение ковенантов, риск дефолта. Банк не хочет "
     "забирать и продавать залог — это переоценка всех аналогичных залогов "
     "портфеля и удар резервами по капиталу; пролонгировать дешевле. Оценщик "
     "оценивает землю «по сопоставимым сделкам», которых нет, потому что никто "
     "не продаёт. Круг замыкается: **оценка залогов держится на том, что залоги "
     "не продаются.** Каждый участник рационален по отдельности — вместе они "
     "воспроизводят режим «пролонгируй и делай вид» (extend and pretend).")
para(doc, "Психологический слой не слабее финансового: признать переплату — значит "
     "назвать имя того, кто покупал. Убыток не признаётся не потому, что его "
     "не видят, а потому, что у него нет добровольного хозяина.")
heading(doc, "Что ломает такие тупики", 2, hnum)
para(doc, "Четыре силы, и все уже включились: время — бриджи имеют сроки, каждая "
     "пролонгация дороже; регулятор — ЦБ фиксирует рост реструктуризаций и "
     "рано или поздно доберётся до честности залоговых оценок; первые вынужденные "
     "продажи — ~60 сделок M&A за 2025 г. создают новые рыночные точки для "
     "оценщиков; и конструкции, позволяющие принять убыток, **не называя его "
     "убытком**. Тупик держится на том, что признание должно быть публичным и "
     "единовременным, — значит, ломается механизмами, которые делают его "
     "приватным и постепенным.")

heading(doc, "Ядро: два спора, один механизм", 1, hnum)
para(doc, "В партнёрских сделках банк × девелопер не решаются переговорами два "
     "спора: «сколько стоит компетенция девелопера» и «сколько стоит его земля». "
     "Оба упираются в одно: стоимость недоказуема на входе. Все конструкции ниже "
     "делают одно и то же — **переводят спор из переговоров в механику сделки**: "
     "вознаграждение компетенции привязывается к проверяемому результату, а "
     "переоценка земли распределяется во времени и между участниками, не требуя "
     "ни от кого публичного признания.")

heading(doc, "Конструкции входа в проект", 1, hnum)
heading(doc, "СП с обязательным co-investment", 2, hnum)
para(doc, "Партнёр-девелопер входит не только компетенцией, но и деньгами — "
     "10–20% equity; доли прибыли пропорциональны капиталу, вклад компетенции "
     "оплачивается управленческим fee и success fee за вехи (РнС, старт продаж, "
     "покрытие эскроу, ввод). Собственные деньги партнёра — единственный аргумент "
     "о качестве его компетенции, который контролирующие структуры принимают "
     "без экспертизы.")
heading(doc, "Fee-девелопмент с опционом", 2, hnum)
para(doc, "Капитал держит 100% проекта; девелопер-оператор работает за fee "
     "(ориентир 3–5% бюджета) плюс опцион на долю прибыли при превышении "
     "целевого IRR. Компетенция оплачивается по факту результата. В России "
     "формат занимает 3–5% проектов против ~75% на западных рынках — ниша "
     "впереди роста.")
heading(doc, "Мезонин с equity-kicker", 2, hnum)
para(doc, "Капитал входит мезонинным долгом с фиксированной доходностью и правом "
     "конверсии части долга в долю при успехе. Держателю капитала — долговой "
     "приоритет; девелоперу — деньги дешевле бриджа; контролёрам — понятная "
     "долговая природа. Рабочая связка с ЗПИФ недвижимости как источником "
     "капитала (сегмент ×1,5 за год, идёт к 1,35 трлн руб.).")
heading(doc, "Поэтапный вход по вехам", 2, hnum)
para(doc, "Капитал докупает долю траншами по мере снятия рисков: концепция — одна "
     "цена, после РнС — другая, после целевого покрытия эскроу — третья. Вклад "
     "компетенции материализуется в дельте стоимости между вехами и не требует "
     "априорной оценки.")

heading(doc, "Конструкции разбора навеса", 1, hnum)
heading(doc, "Взнос земли в СП с субординацией", 2, hnum)
para(doc, "Девелопер вносит площадку в СП по согласованной стоимости, близкой к "
     "книжной, — лицо сохранено, дефолта по бриджу нет. Но его доля прибыли "
     "субординирована: сначала возврат капитала партнёра с доходностью, затем "
     "его доля. Не вырос рынок — дисконт реализовался тихо, через распределение; "
     "вырос — девелопер отстоял цену. Убыток принят, но не объявлен: механизм "
     "отложенного признания, приемлемый для обеих сторон.")
heading(doc, "Опцион вместо покупки", 2, hnum)
para(doc, "Покупать землю в затоваренном рынке сегодня — переплачивать. Опцион — "
     "нет: капитал платит премию, которой девелоперу хватает на обслуживание "
     "бриджа, и получает право входа через 1–2 года по формуле от будущей "
     "оценки. Девелопер получает кислород, банк — обслуживаемый кредит, капитал — "
     "вход по завтрашней честной цене без сегодняшнего спора о вчерашней. Цену "
     "ожидания платит тот, кто верит в разворот.")
heading(doc, "Конверсия бриджа в долю", 2, hnum)
