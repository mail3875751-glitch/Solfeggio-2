# -*- coding: utf-8 -*-
"""Сборка документа «Конструкция-визитка» — для кулуарных разговоров."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from docx_helpers import *

OUT = sys.argv[1] if len(sys.argv) > 1 else "vizitka.docx"
NB = " "

doc = new_document("Конструкция-визитка", "материал для обсуждения")
hnum = add_multilevel_heading_numbering(doc)

doc_title(doc, "Партнёрство банковского капитала и девелоперской компетенции",
          "Рабочие конструкции сделок: материал для обсуждения на отраслевых площадках",
          f"Август 2026{NB}г. · версия 0.1 (черновик для кулуарных разговоров, не оферта)")

heading(doc, "Почему это своевременно", 1, hnum)
para(doc, "Рынок сам сформулировал запрос: центральная финансовая тема отрасли "
     "2026 года — переход банков «от кредитования к совместному бизнесу». "
     "Три обстоятельства делают партнёрские конструкции насущными:")
nb = add_list_numbering(doc, "decimal")
list_item(doc, "**Земля недоступна в кредит.** Бридж под площадку на пике ставки стоил "
          "25–26% годовых и убивал экономику проекта; рынок земли фактически стоял. "
          "Вход в новые площадки теперь идёт через КРТ, выкуп у проблемных игроков "
          "и партнёрства с землевладельцами.", nb)
list_item(doc, "**Банкам не хватает equity в проектах.** Требования к собственному участию "
          "выросли, покрытие долга эскроу упало с 88% до ~70%, андеррайтинг смотрит "
          "на всю группу. Проекты с землёй и разрешением получают отказы из-за "
          "расчётного покрытия.", nb)
list_item(doc, "**Компетенция и капитал разъехались по разным рукам.** У девелоперов — "
          "команды и опыт, но дорогие деньги; у держателей капитала — деньги, но нет "
          "аппетита и умения быть техническим заказчиком. Нужна конструкция, "
          "в которой вклад каждой стороны измерим и защитим.", nb)

heading(doc, "Ядро проблемы: чем доказать стоимость компетенции", 1, hnum)
para(doc, "Наивная схема «партнёр входит компетенцией, капитал — деньгами, прибыль "
     "пополам» не проходит контрольные контуры держателей капитала: стоимость "
     "компетенции недоказуема на входе. Все рабочие конструкции ниже решают одну "
     "и ту же задачу: **привязать вознаграждение компетенции к проверяемому "
     "результату, а не к обещанию**.")

heading(doc, "Четыре рабочие конструкции", 1, hnum)
heading(doc, "СП с обязательным co-investment", 2, hnum)
para(doc, "Партнёр-девелопер входит не только компетенцией, но и деньгами — "
     "10–20% equity. Доли прибыли пропорциональны капиталу; вклад компетенции "
     "оплачивается отдельно — управленческим fee и success fee за достижение "
     "вех (получение РнС, старт продаж, покрытие эскроу, ввод). Ключевой эффект: "
     "партнёр рискует своими деньгами — это единственный аргумент о качестве "
     "его компетенции, который контролирующие структуры принимают без экспертизы.")
heading(doc, "Fee-девелопмент с опционом", 2, hnum)
para(doc, "Капитал держит 100% проекта; девелопер работает как оператор за "
     "фиксированное вознаграждение (ориентир рынка — 3–5% бюджета) плюс опцион "
     "на долю прибыли при превышении целевого IRR. Компетенция оплачивается "
     "строго по факту результата: не достиг порога — получил только fee. "
     "В России формат занимает лишь 3–5% проектов против ~75% на западных рынках — "
     "ниша впереди роста, тема консолидации без M&A.")
heading(doc, "Мезонин с equity-kicker", 2, hnum)
para(doc, "Капитал входит мезонинным долгом с фиксированной доходностью и правом "
     "конверсии части долга в долю при успехе проекта. Для держателя капитала — "
     "защита долгового приоритета; для девелопера — деньги дешевле бриджа; "
     "для контролёров — понятная долговая природа инструмента. Рабочая связка "
     "с ЗПИФ недвижимости как источником капитала: сегмент вырос в 1,5 раза "
     "за год и идёт к 1,35 трлн ₽.", size=11)
heading(doc, "Поэтапный вход по вехам", 2, hnum)
para(doc, "Капитал докупает долю траншами по мере снятия рисков: вход на этапе "
     "концепции — по одной цене, после РнС — по другой, после выхода на "
     "целевое покрытие эскроу — по третьей. Вклад компетенции девелопера "
     "материализуется в дельте стоимости между вехами и потому не требует "
     "априорной оценки. Конструкция снимает главный страх капитала — заплатить "
     "вперёд за недоказанное.")

callout(doc, "ОБЩИЙ ПРИНЦИП",
        ["Во всех четырёх конструкциях спор «сколько стоит компетенция» переведён "
         "из переговоров в механику сделки: вехи, опционы, co-investment и дельта "
         "стоимости делают вклад девелопера **измеримым по факту**. Это и есть "
         "ответ на вопрос, почему прежние партнёрские схемы не проходили "
         "контрольные контуры."])

heading(doc, "Что это даёт банку-кредитору", 1, hnum)
nb2 = add_list_numbering(doc, "bullet")
list_item(doc, "Партнёрское equity в проекте повышает покрытие и LLCR — проект "
          "проходит кредитный комитет, который сегодня его отклоняет.", nb2)
list_item(doc, "Профессиональный оператор с оплатой за результат снижает риск "
          "срыва графика — при 58% объектов с переносами сроков это прямой "
          "фактор качества портфеля.", nb2)
list_item(doc, "Конструкции дают банку роль партнёра, а не только кредитора, — "
          "в русле отраслевого тренда «от кредитования к совместному бизнесу».", nb2)

heading(doc, "Три вопроса для разговора", 1, hnum)
para(doc, "Материал выше — не презентация со сцены, а опора для кулуарного "
     "диалога. Вопросы, с которых он начинается:")
nb3 = add_list_numbering(doc, "decimal")
list_item(doc, "Как вы сейчас решаете вход в новую площадку без живых денег — "
          "КРТ, рассрочка от собственника, партнёрство? Что из этого реально "
          "прошло кредитный комитет?", nb3)
list_item(doc, "Если бы капитал был готов войти в ваш проект equity — на каких "
          "условиях вы бы согласились делить прибыль? Что для вас приемлемее: "
          "co-investment, опцион, поэтапная продажа долей?", nb3)
list_item(doc, "Какая из ваших заявок на проектное финансирование за последний "
          "год не прошла — и знаете ли вы, по какому именно расчётному "
          "параметру?", nb3)
para(doc, "")
para(doc, "Материал подготовлен для обсуждения; расчётные модели конструкций "
     "(квартальный CF, LLCR, чувствительность) предоставляются под конкретный "
     "проект.", size=9, italic=True, color=T["muted"], align="left")

doc.save(OUT)
print("OK:", OUT)
